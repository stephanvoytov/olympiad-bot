olympiads = []
used_slugs = set()

for num, name, organizer, profiles, level in OLYMPIADS:
    slug = slugify(name)
    # Ensure unique slug
    base_slug = slug
    counter = 1
    while slug in used_slugs:
        slug = f"{base_slug}-{counter}"
        counter += 1
    used_slugs.add(slug)

    # Determine tags from profiles
    tags = set()
    for pname, _ in profiles:
        pname_lower = pname.lower()
        if any(x in pname_lower for x in ["математик", "алгебр", "геометр", "статистик", "вероятн"]):
            tags.add("математика")
        if any(x in pname_lower for x in ["физик", "механик"]):
            tags.add("физика")
        if any(x in pname_lower for x in ["информатик", "программиров", "компьютер", "робототехник", "ии", "искусственн"]):
            tags.add("информатика")
        if any(x in pname_lower for x in ["химик", "химия"]):
            tags.add("химия")
        if any(x in pname_lower for x in ["биолог", "генетик"]):
            tags.add("биология")
        if any(x in pname_lower for x in ["историк", "история"]):
            tags.add("история")
        if any(x in pname_lower for x in ["обществ", "право", "юридик", "юриспруденц"]):
            tags.add("обществознание")
        if any(x in pname_lower for x in ["экономик", "финанс"]):
            tags.add("экономика")
        if any(x in pname_lower for x in ["географ", "геолог"]):
            tags.add("география")
        if any(x in pname_lower for x in ["литератур", "язык", "лингвистик", "филолог"]):
            tags.add("языки")
        if any(x in pname_lower for x in ["рисунок", "живопис", "дизайн", "график", "искусств", "композиц"]):
            tags.add("искусство")
        if any(x in pname_lower for x in ["инженер", "техник", "технолог"]):
            tags.add("инженерия")
    tags = sorted(tags) or ["олимпиада"]

    benefits = make_benefits(level)
    stages = make_stages(level)

    profile_entries = []
    for pname, subject_group in profiles:
        pslug = slugify(pname)
        # Ensure unique profile slug within olympiad
        base_pslug = pslug
        pcounter = 1
        existing_slugs = [p["slug"] for p in profile_entries]
        while pslug in existing_slugs:
            pslug = f"{base_pslug}-{pcounter}"
            pcounter += 1
        profile_entries.append({
            "slug": pslug,
            "name": pname,
            "level": level,
            "benefits": benefits.copy(),
            "stages": stages,
        })

    olympiads.append({
        "id": slug,
        "name": name,
        "organizer": organizer,
        "url": "",
        "registration_url": "",
        "tags": tags,
        "profiles": profile_entries,
    })

